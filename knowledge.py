DOC_TYPE_MAPPING = {
    "паспорт": "passport_rf",
    "аттестат": "attestat",
    "приложение": "attestat_prilozhenie",
    "перевод": "attestat_translation",
    "апостиль": "attestat_apostille",
    "нострификация": "nostrification",
    "медицинская": "medical_cert",
    "медсправка": "medical_cert",
    "справка": "medical_cert",
    "фото": "photos",
    "ент": "ent_cert",
    "егэ": "ent_cert",
    "заявление": "application_form",
    "приписное": "military_doc",
    "военный": "military_doc",
    "военный билет": "military_doc",
    "свидетельство о рождении": "birth_cert",
    "свидетельство": "birth_cert",
}


def detect_doc_type(text: str) -> str:
    """Try to detect document type from filename or caption."""
    text_lower = text.lower()
    for keyword, doc_type in DOC_TYPE_MAPPING.items():
        if keyword in text_lower:
            return doc_type
    return "other"
